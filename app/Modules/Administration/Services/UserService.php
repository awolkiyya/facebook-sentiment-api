<?php

namespace App\Modules\Administration\Services;

use App\Models\User;
use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

class UserService
{
    /**
     * List users with filtering, searching, sorting and pagination.
     */
    public function paginate(array $filters = []): LengthAwarePaginator
    {
        $query = User::query()
            ->with('roles')
            ->when(
                !empty($filters['search']),
                function (Builder $query) use ($filters): void {
                    $search = trim($filters['search']);

                    $query->where(function (Builder $query) use ($search): void {
                        $query
                            ->where('name', 'ilike', "%{$search}%")
                            ->orWhere('email', 'ilike', "%{$search}%");
                    });
                }
            )
            ->when(
                isset($filters['is_active']),
                function (Builder $query) use ($filters): void {
                    $query->where(
                        'is_active',
                        filter_var(
                            $filters['is_active'],
                            FILTER_VALIDATE_BOOLEAN
                        )
                    );
                }
            )
            ->when(
                isset($filters['role']),
                function (Builder $query) use ($filters): void {
                    $query->whereHas(
                        'roles',
                        fn (Builder $roleQuery) => $roleQuery
                            ->where('name', $filters['role'])
                    );
                }
            );

        $sortBy = $filters['sort_by'] ?? 'created_at';
        $sortDirection = $filters['sort_direction'] ?? 'desc';

        $allowedSorts = [
            'name',
            'email',
            'created_at',
            'last_login_at',
            'is_active',
        ];

        if (!in_array($sortBy, $allowedSorts, true)) {
            $sortBy = 'created_at';
        }

        if (!in_array($sortDirection, ['asc', 'desc'], true)) {
            $sortDirection = 'desc';
        }

        return $query
            ->orderBy($sortBy, $sortDirection)
            ->paginate(
                min(
                    (int) ($filters['per_page'] ?? 20),
                    100
                )
            )
            ->withQueryString();
    }


    /**
     * Create a new user.
     */
    public function create(array $data): User
    {
        return DB::transaction(function () use ($data): User {

            $roles = $data['roles'] ?? [];

            unset($data['roles']);

            /*
             * UUID is automatically generated by HasUuids.
             */
            $user = User::create($data);

            /*
             * Assign roles through Spatie Permission.
             */
            if (!empty($roles)) {
                $user->syncRoles($roles);
            }

            return $user->load('roles');
        });
    }


    /**
     * Update a user.
     */
    public function update(User $user, array $data): User
    {
        return DB::transaction(function () use ($user, $data): User {

            $roles = $data['roles'] ?? null;

            unset($data['roles']);

            /*
             * Prevent an update operation from accidentally modifying
             * security-controlled authentication fields.
             */
            unset(
                $data['failed_login_attempts'],
                $data['last_failed_login_at'],
                $data['locked_until'],
                $data['lockout_count'],
                $data['mfa_enabled'],
                $data['mfa_confirmed_at']
            );

            $user->update($data);

            if ($roles !== null) {
                $user->syncRoles($roles);
            }

            return $user->refresh()->load('roles');
        });
    }


    /**
     * Update account active/inactive status.
     */
    public function updateStatus(User $user, bool $isActive): User
    {
        return DB::transaction(function () use ($user, $isActive): User {

            $user->update([
                'is_active' => $isActive,
            ]);

            /*
             * If an account is disabled, immediately invalidate
             * the current lockout state.
             */
            if (!$isActive) {
                $user->update([
                    'locked_until' => null,
                ]);
            }

            return $user->refresh()->load('roles');
        });
    }


    /**
     * Reset a user's password.
     */
    public function resetPassword(User $user, string $password): User
    {
        return DB::transaction(function () use ($user, $password): User {

            $user->update([
                'password' => $password,
                'failed_login_attempts' => 0,
                'last_failed_login_at' => null,
                'locked_until' => null,
            ]);

            return $user->refresh()->load('roles');
        });
    }


    /**
     * Unlock a user account.
     */
    public function unlock(User $user): User
    {
        return DB::transaction(function () use ($user): User {

            $user->update([
                'failed_login_attempts' => 0,
                'last_failed_login_at' => null,
                'locked_until' => null,
            ]);

            return $user->refresh()->load('roles');
        });
    }


    /**
     * Soft delete a user.
     */
    public function delete(User $user): void
    {
        DB::transaction(function () use ($user): void {
            $user->delete();
        });
    }
}