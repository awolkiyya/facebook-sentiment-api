<?php

namespace App\Modules\Auth\Requests;

use Illuminate\Foundation\Http\FormRequest;

class MfaLoginVerifyRequest extends FormRequest
{
    /**
     * Determine whether the user is authorized
     * to make this request.
     *
     * IMPORTANT:
     *
     * The user is NOT authenticated yet.
     *
     * Authentication is completed only after:
     *
     *     challenge_id + MFA code
     *
     * have been successfully verified.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Validation rules.
     */
    public function rules(): array
    {
        return [
            /*
            |--------------------------------------------------------------------------
            | MFA Challenge ID
            |--------------------------------------------------------------------------
            |
            | UUID generated by MfaLoginChallengeService.
            |
            */

            'challenge_id' => [
                'required',
                'string',
                'uuid',
            ],

            /*
            |--------------------------------------------------------------------------
            | MFA Code
            |--------------------------------------------------------------------------
            |
            | Supports:
            |
            |     TOTP:
            |         6 digits
            |
            |     Recovery code:
            |         Example:
            |         ABCD-EFGH-IJKL
            |
            | MfaService is responsible for determining
            | which type of code was supplied.
            |
            */

            'code' => [
                'required',
                'string',
                'max:100',
            ],
        ];
    }

    /**
     * Custom validation messages.
     */
    public function messages(): array
    {
        return [
            'challenge_id.required' => 'The MFA challenge is required.',
            'challenge_id.uuid' => 'The MFA challenge is invalid.',

            'code.required' => 'The authentication or recovery code is required.',
            'code.max' => 'The authentication or recovery code is invalid.',
        ];
    }
}