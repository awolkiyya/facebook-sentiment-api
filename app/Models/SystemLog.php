<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class SystemLog extends Model
{
    /**
     * System logs are immutable audit records.
     *
     * The table only contains created_at, not updated_at.
     */
    public $timestamps = false;

    /**
     * Table associated with the model.
     */
    protected $table = 'system_logs';

    /**
     * Mass assignable attributes.
     *
     * Never include sensitive credentials such as:
     * - access tokens
     * - refresh tokens
     * - passwords
     * - API secrets
     */
    protected $fillable = [
        'user_id',
        'action',
        'module',
        'status',
        'severity',
        'resource_type',
        'resource_id',
        'description',
        'old_values',
        'new_values',
        'request_id',
        'http_method',
        'endpoint',
        'ip_address',
        'user_agent',
        'duration_ms',
        'metadata',
        'created_at',
    ];

    /**
     * Attribute casting.
     */
    protected function casts(): array
    {
        return [
            'old_values' => 'array',
            'new_values' => 'array',
            'metadata' => 'array',

            'duration_ms' => 'integer',

            'created_at' => 'datetime',
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Relationships
    |--------------------------------------------------------------------------
    */

    /**
     * User who performed the action.
     *
     * Nullable because logs can be generated by:
     * - queue workers
     * - scheduled jobs
     * - webhooks
     * - system processes
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /*
    |--------------------------------------------------------------------------
    | Query Scopes
    |--------------------------------------------------------------------------
    */

    /**
     * Filter by action.
     */
    public function scopeAction(
        Builder $query,
        ?string $action
    ): Builder {
        return $query->when(
            $action,
            fn (Builder $query) => $query->where('action', $action)
        );
    }

    /**
     * Filter by module.
     */
    public function scopeModule(
        Builder $query,
        ?string $module
    ): Builder {
        return $query->when(
            $module,
            fn (Builder $query) => $query->where('module', $module)
        );
    }

    /**
     * Filter by status.
     */
    public function scopeStatus(
        Builder $query,
        ?string $status
    ): Builder {
        return $query->when(
            $status,
            fn (Builder $query) => $query->where('status', $status)
        );
    }

    /**
     * Filter by severity.
     */
    public function scopeSeverity(
        Builder $query,
        ?string $severity
    ): Builder {
        return $query->when(
            $severity,
            fn (Builder $query) => $query->where('severity', $severity)
        );
    }

    /**
     * Filter by user.
     */
    public function scopeForUser(
        Builder $query,
        ?string $userId
    ): Builder {
        return $query->when(
            $userId,
            fn (Builder $query) => $query->where('user_id', $userId)
        );
    }

    /**
     * Filter by resource type.
     */
    public function scopeResourceType(
        Builder $query,
        ?string $resourceType
    ): Builder {
        return $query->when(
            $resourceType,
            fn (Builder $query) => $query->where(
                'resource_type',
                $resourceType
            )
        );
    }

    /**
     * Filter by resource ID.
     */
    public function scopeResourceId(
        Builder $query,
        ?string $resourceId
    ): Builder {
        return $query->when(
            $resourceId,
            fn (Builder $query) => $query->where(
                'resource_id',
                $resourceId
            )
        );
    }

    /**
     * Filter by request ID.
     */
    public function scopeRequestId(
        Builder $query,
        ?string $requestId
    ): Builder {
        return $query->when(
            $requestId,
            fn (Builder $query) => $query->where(
                'request_id',
                $requestId
            )
        );
    }

    /**
     * Filter by IP address.
     */
    public function scopeIpAddress(
        Builder $query,
        ?string $ipAddress
    ): Builder {
        return $query->when(
            $ipAddress,
            fn (Builder $query) => $query->where(
                'ip_address',
                $ipAddress
            )
        );
    }

    /**
     * Filter logs from a specific date/time.
     */
    public function scopeFromDate(
        Builder $query,
        ?string $from
    ): Builder {
        return $query->when(
            $from,
            fn (Builder $query) => $query->where(
                'created_at',
                '>=',
                $from
            )
        );
    }

    /**
     * Filter logs until a specific date/time.
     */
    public function scopeToDate(
        Builder $query,
        ?string $to
    ): Builder {
        return $query->when(
            $to,
            fn (Builder $query) => $query->where(
                'created_at',
                '<=',
                $to
            )
        );
    }

    /**
     * General search across commonly useful audit fields.
     */
    public function scopeSearch(
        Builder $query,
        ?string $search
    ): Builder {
        return $query->when(
            $search,
            function (Builder $query) use ($search) {
                $query->where(function (Builder $query) use ($search) {
                    $query
                        ->where('action', 'ILIKE', "%{$search}%")
                        ->orWhere('module', 'ILIKE', "%{$search}%")
                        ->orWhere('description', 'ILIKE', "%{$search}%")
                        ->orWhere('resource_type', 'ILIKE', "%{$search}%")
                        ->orWhere('resource_id', 'ILIKE', "%{$search}%")
                        ->orWhere('request_id', 'ILIKE', "%{$search}%")
                        ->orWhere('ip_address', 'ILIKE', "%{$search}%")
                        ->orWhere('endpoint', 'ILIKE', "%{$search}%")
                        ->orWhereHas(
                            'user',
                            function (Builder $userQuery) use ($search) {
                                $userQuery
                                    ->where('name', 'ILIKE', "%{$search}%")
                                    ->orWhere(
                                        'email',
                                        'ILIKE',
                                        "%{$search}%"
                                    );
                            }
                        );
                });
            }
        );
    }

    /**
     * Sort by a whitelisted field.
     *
     * This prevents arbitrary SQL column injection through
     * sort_by query parameters.
     */
    public function scopeSortBy(
        Builder $query,
        ?string $field,
        ?string $direction = 'desc'
    ): Builder {
        $allowedFields = [
            'id',
            'created_at',
            'action',
            'module',
            'status',
            'severity',
            'user_id',
            'resource_type',
            'resource_id',
            'request_id',
            'duration_ms',
        ];

        $field = in_array($field, $allowedFields, true)
            ? $field
            : 'created_at';

        $direction = strtolower((string) $direction) === 'asc'
            ? 'asc'
            : 'desc';

        return $query->orderBy($field, $direction);
    }

    /*
    |--------------------------------------------------------------------------
    | Convenience Methods
    |--------------------------------------------------------------------------
    */

    /**
     * Determine whether the log was successful.
     */
    public function isSuccessful(): bool
    {
        return $this->status === 'SUCCESS';
    }

    /**
     * Determine whether the log failed.
     */
    public function isFailed(): bool
    {
        return $this->status === 'FAILED';
    }

    /**
     * Determine whether the action was denied.
     */
    public function isDenied(): bool
    {
        return $this->status === 'DENIED';
    }

    /**
     * Determine whether this is a warning.
     */
    public function isWarning(): bool
    {
        return $this->severity === 'WARNING';
    }

    /**
     * Determine whether this is an error.
     */
    public function isError(): bool
    {
        return $this->severity === 'ERROR';
    }

    /**
     * Determine whether this is a critical event.
     */
    public function isCritical(): bool
    {
        return $this->severity === 'CRITICAL';
    }
}
