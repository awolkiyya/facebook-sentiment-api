<?php

namespace App\Http\Controllers;

use App\Http\Controllers\Controller;
use App\Http\Requests\MfaConfirmRequest;
use App\Http\Requests\MfaDisableRequest;
use App\Http\Requests\MfaVerifyRequest;
use App\Services\MfaService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Hash;
use Illuminate\Validation\ValidationException;
use RuntimeException;
use Illuminate\Support\Facades\Log;


class MfaController extends Controller
{
    public function __construct(
        private readonly MfaService $mfaService,
    ) {
    }

    /**
     * Get the authenticated user's MFA status.
     */
    public function status(Request $request): JsonResponse
    {
        $user = $request->user();

        return response()->json([
            'success' => true,
            'message' => 'MFA status retrieved successfully.',
            'data' => $this->mfaService->getStatus($user),
        ]);
    }

    /**
     * Start TOTP setup.
     *
     * Returns the secret and otpauth URL required to configure
     * an authenticator application.
     */
    public function setup(Request $request): JsonResponse
    {
        $user = $request->user();

        try {
            $data = $this->mfaService->startTotpSetup($user);

            return response()->json([
                'success' => true,
                'message' => 'Two-factor authentication setup started.',
                'data' => $data,
            ]);
        } catch (RuntimeException $e) {
            return response()->json([
                'success' => false,
                'message' => $e->getMessage(),
            ], 422);
        }
    }

    /**
     * Confirm TOTP setup.
     *
     * The user must provide the 6-digit code generated
     * by their authenticator application.
     */
    public function confirm(
        MfaConfirmRequest $request
    ): JsonResponse {
        $user = $request->user();

        $validated = $request->validated();

        try {
            $data = $this->mfaService->confirmTotpSetup(
                $user,
                $validated['code']
            );

            return response()->json([
                'success' => true,
                'message' => 'Two-factor authentication enabled successfully.',
                'data' => $data,
            ]);
        } catch (RuntimeException $e) {
            throw ValidationException::withMessages([
                'code' => [
                    $e->getMessage(),
                ],
            ]);
        }
    }

   /**
 * Verify an MFA code during the login challenge.
 *
 * Accepts either:
 * - TOTP code
 * - Recovery code
 *
 * The user is resolved from the MFA login challenge because
 * the Laravel authenticated user does not exist yet at this stage.
 */
public function verify(
    MfaVerifyRequest $request
): JsonResponse {
    $requestId = $request->header('X-Request-ID');

    Log::info('MFA verification started.', [
        'request_id' => $requestId,
        'ip' => $request->ip(),
        'user_agent' => $request->userAgent(),
        'route' => $request->route()?->getName(),
        'method' => $request->method(),
    ]);

    try {
        /*
         * -----------------------------------------------------------
         * 1. Validate request
         * -----------------------------------------------------------
         */
        $validated = $request->validated();

        Log::info('MFA verification request validated.', [
            'request_id' => $requestId,
            'challenge_id' => $validated['challenge_id'] ?? null,
            'has_code' => !empty($validated['code']),
            'code_length' => isset($validated['code'])
                ? strlen((string) $validated['code'])
                : 0,
        ]);

        /*
         * -----------------------------------------------------------
         * 2. Resolve MFA login challenge
         * -----------------------------------------------------------
         *
         * IMPORTANT:
         * Do not accept user_id from the frontend.
         *
         * The challenge_id is generated by the backend during
         * password authentication and is used to identify the
         * pending login attempt.
         */
        $challenge = $this->mfaLoginChallengeService->findValid(
            $validated['challenge_id']
        );

        if ($challenge === null) {
            Log::warning('MFA verification failed: invalid or expired challenge.', [
                'request_id' => $requestId,
                'challenge_id' => $validated['challenge_id'] ?? null,
                'ip' => $request->ip(),
            ]);

            throw ValidationException::withMessages([
                'challenge_id' => [
                    'The MFA challenge is invalid or has expired.',
                ],
            ]);
        }

        /*
         * -----------------------------------------------------------
         * 3. Resolve the user from the challenge
         * -----------------------------------------------------------
         */
        $user = $challenge->user;

        if ($user === null) {
            Log::error('MFA verification failed: challenge has no user.', [
                'request_id' => $requestId,
                'challenge_id' => $challenge->id,
            ]);

            throw ValidationException::withMessages([
                'challenge_id' => [
                    'The MFA challenge is invalid.',
                ],
            ]);
        }

        Log::info('MFA challenge user resolved.', [
            'request_id' => $requestId,
            'challenge_id' => $challenge->id,
            'user_id' => $user->id,
        ]);

        /*
         * -----------------------------------------------------------
         * 4. Verify MFA code
         * -----------------------------------------------------------
         */
        Log::info('Calling MFA verification service.', [
            'request_id' => $requestId,
            'challenge_id' => $challenge->id,
            'user_id' => $user->id,
        ]);

        $method = $this->mfaService->verify(
            $user,
            $validated['code']
        );

        Log::info('MFA verification service completed.', [
            'request_id' => $requestId,
            'challenge_id' => $challenge->id,
            'user_id' => $user->id,
            'verification_method' => $method,
            'verified' => $method !== null,
        ]);

        /*
         * -----------------------------------------------------------
         * 5. Reject invalid MFA code
         * -----------------------------------------------------------
         */
        if ($method === null) {
            Log::warning('MFA verification failed: invalid or expired code.', [
                'request_id' => $requestId,
                'challenge_id' => $challenge->id,
                'user_id' => $user->id,
                'ip' => $request->ip(),
            ]);

            throw ValidationException::withMessages([
                'code' => [
                    'The verification code is invalid or has expired.',
                ],
            ]);
        }

        /*
         * -----------------------------------------------------------
         * 6. MFA verified successfully
         * -----------------------------------------------------------
         *
         * At this point the MFA challenge must be consumed and
         * the login session/token must be completed.
         *
         * The exact authentication call depends on how your
         * existing login service creates the Laravel session/token.
         */
        Log::info('MFA verification successful.', [
            'request_id' => $requestId,
            'challenge_id' => $challenge->id,
            'user_id' => $user->id,
            'verification_method' => $method,
        ]);

        /*
         * Mark the challenge as consumed.
         *
         * Use your actual challenge service method here if you
         * already have one, for example:
         *
         * $this->mfaLoginChallengeService->consume($challenge);
         */
        $this->mfaLoginChallengeService->consume($challenge);

        /*
         * Complete the pending authentication.
         *
         * This should use the same authentication mechanism as
         * your normal web login.
         *
         * Example:
         *
         * Auth::login($user);
         *
         * If you use Sanctum/API tokens instead, generate the
         * appropriate token here instead.
         */

        Log::info('MFA login challenge consumed.', [
            'request_id' => $requestId,
            'challenge_id' => $challenge->id,
            'user_id' => $user->id,
        ]);

        return response()->json([
            'success' => true,
            'message' => 'Two-factor authentication verified successfully.',
            'data' => [
                'verified' => true,
                'method' => $method,
                'user' => [
                    'id' => $user->id,
                    'name' => $user->name,
                    'email' => $user->email,
                ],
            ],
        ]);
    } catch (ValidationException $e) {
        Log::warning('MFA verification validation exception.', [
            'request_id' => $requestId,
            'errors' => $e->errors(),
        ]);

        throw $e;
    } catch (\Throwable $e) {
        Log::error('MFA verification failed with unexpected exception.', [
            'request_id' => $requestId,
            'exception' => get_class($e),
            'message' => $e->getMessage(),
            'file' => $e->getFile(),
            'line' => $e->getLine(),
            'trace' => $e->getTraceAsString(),
        ]);

        throw $e;
    }
}

    /**
     * Get recovery-code status.
     *
     * Does not return the actual recovery codes.
     */
    public function recoveryCodesStatus(
        Request $request
    ): JsonResponse {
        $user = $request->user();

        return response()->json([
            'success' => true,
            'message' => 'Recovery code status retrieved successfully.',
            'data' => $this->mfaService->getRecoveryCodeStatus($user),
        ]);
    }

    /**
     * Regenerate recovery codes.
     *
     * Existing recovery codes become invalid immediately.
     */
    public function regenerateRecoveryCodes(
        Request $request
    ): JsonResponse {
        $user = $request->user();

        try {
            $codes = $this->mfaService->regenerateRecoveryCodes($user);

            return response()->json([
                'success' => true,
                'message' => 'Recovery codes regenerated successfully.',
                'data' => [
                    'recovery_codes' => $codes,
                ],
            ]);
        } catch (RuntimeException $e) {
            return response()->json([
                'success' => false,
                'message' => $e->getMessage(),
            ], 422);
        }
    }

    /**
     * Disable TOTP MFA.
     *
     * Requires:
     * - Current password
     * - Current TOTP code
     */
    public function disable(
        MfaDisableRequest $request
    ): JsonResponse {
        $user = $request->user();

        $validated = $request->validated();

        /*
         * Verify the user's current password before allowing
         * MFA to be disabled.
         */
        if (!Hash::check(
            $validated['password'],
            $user->password
        )) {
            throw ValidationException::withMessages([
                'password' => [
                    'The password is incorrect.',
                ],
            ]);
        }

        /*
         * Verify the current TOTP code.
         *
         * Recovery codes are intentionally not accepted here.
         * Disabling MFA is a sensitive security operation.
         */
        if (!$this->mfaService->verifyTotp(
            $user,
            $validated['code']
        )) {
            throw ValidationException::withMessages([
                'code' => [
                    'The verification code is invalid or has expired.',
                ],
            ]);
        }

        try {
            $this->mfaService->disableTotp($user);

            return response()->json([
                'success' => true,
                'message' => 'Two-factor authentication disabled successfully.',
                'data' => [
                    'enabled' => false,
                ],
            ]);
        } catch (RuntimeException $e) {
            return response()->json([
                'success' => false,
                'message' => $e->getMessage(),
            ], 422);
        }
    }

    /**
     * Cancel an unfinished TOTP setup.
     */
    public function cancelSetup(
        Request $request
    ): JsonResponse {
        $user = $request->user();

        $this->mfaService->cancelTotpSetup($user);

        return response()->json([
            'success' => true,
            'message' => 'Two-factor authentication setup cancelled.',
        ]);
    }
}